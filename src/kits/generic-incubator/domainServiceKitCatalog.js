export function createDomainKitContractSnapshot({ engine = null } = {}) {
  const installed = Object.entries(engine?.domainServiceKits ?? {}).map(([id, metadata]) => ({
    id,
    apiName: metadata.apiName,
    domain: metadata.domain,
    domainPath: metadata.domainPath ?? `n:${metadata.domain}`,
    layer: metadata.layer ?? "runtime-installed",
    stability: metadata.stability,
    version: metadata.version,
  }));

  return structuredClone({
    version: KIT_CONTRACT_VERSION,
    templateFields: KIT_CONTRACT_FIELDS,
    generic: {
      count: genericIncubatorKitContracts.length,
      contracts: genericIncubatorKitContracts,
    },
    goldRush: {
      count: goldRushKitContracts.length,
      contracts: goldRushKitContracts,
    },
    pairings: goldRushKitPairings,
    installed,
  });
}

export function validateDomainKitContractCatalog({
  generic = genericIncubatorKitContracts,
  goldRush = goldRushKitContracts,
  pairings = goldRushKitPairings,
  docs = null,
} = {}) {
  const failures = [];
  const genericDomainPaths = new Set();
  const goldRushDomainPaths = new Set();

  for (const contract of generic) {
    validateContract(contract, failures, { layer: "generic-incubator" });
    if (genericDomainPaths.has(contract.domainPath)) failures.push(`duplicate-generic-domain-path:${contract.domainPath}`);
    genericDomainPaths.add(contract.domainPath);
    const genericText = JSON.stringify({
      purpose: contract.purpose,
      publicApi: contract.publicApi,
      internalApi: contract.internalApi,
      events: contract.events,
      snapshot: contract.snapshot,
      dataExposed: contract.dataExposed,
      graduationRule: contract.graduationRule,
    }).toLowerCase();
    if (genericText.includes("goldrush") || genericText.includes("gold rush")) {
      failures.push(`generic-contract-contains-game-name:${contract.domainPath}`);
    }
  }

  for (const contract of goldRush) {
    validateContract(contract, failures, { layer: "goldrush-custom" });
    if (!contract.domainPath.startsWith("n:goldrush:")) failures.push(`goldrush-contract-wrong-domain:${contract.domainPath}`);
    if (goldRushDomainPaths.has(contract.domainPath)) failures.push(`duplicate-goldrush-domain-path:${contract.domainPath}`);
    goldRushDomainPaths.add(contract.domainPath);
  }

  for (const pairing of pairings) {
    if (!genericDomainPaths.has(pairing.genericDomainPath)) failures.push(`pairing-missing-generic:${pairing.genericDomainPath}`);
    if (!goldRushDomainPaths.has(pairing.goldRushDomainPath)) failures.push(`pairing-missing-goldrush:${pairing.goldRushDomainPath}`);
  }

  if (docs) {
    for (const contract of [...generic, ...goldRush]) {
      if (!docs.includes(contract.domainPath)) failures.push(`docs-missing-domain-path:${contract.domainPath}`);
    }
  }

  return {
    passed: failures.length === 0,
    failures,
    counts: {
      generic: generic.length,
      goldRush: goldRush.length,
      pairings: pairings.length,
    },
  };
}

export function domainPathToServiceDomain(domainPath) {
  return domainPath.replace(/^n:/, "").replaceAll(":", "-");
}

function validateContract(contract, failures, { layer }) {
  if (contract.layer !== layer) failures.push(`wrong-layer:${contract.domainPath ?? "unknown"}`);
  for (const field of KIT_CONTRACT_FIELDS) {
    if (!Object.prototype.hasOwnProperty.call(contract, field)) failures.push(`missing-${field}:${contract.domainPath ?? "unknown"}`);
  }
  if (!/^n:[a-z][a-z0-9-]*(?::[a-z][a-z0-9-]*)+$/.test(contract.domainPath ?? "")) {
    failures.push(`invalid-domain-path:${contract.domainPath ?? "unknown"}`);
  }
  for (const field of ["publicApi", "internalApi", "events", "snapshot", "dataExposed"]) {
    if (!Array.isArray(contract[field]) || contract[field].length === 0) failures.push(`empty-${field}:${contract.domainPath}`);
  }
  for (const field of ["purpose", "reset", "validator", "graduationRule"]) {
    if (typeof contract[field] !== "string" || contract[field].trim().length === 0) failures.push(`empty-${field}:${contract.domainPath}`);
  }
}
