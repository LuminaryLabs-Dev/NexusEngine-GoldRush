const defaultGraduationRule = "Promotable when the API is neutral, deterministic, documented, resettable, snapshot-safe, and validated outside one game.";
const defaultReset = "Clear runtime-local buffers and rebuild deterministic state from public API input plus minimal config.";

function createGenericContract(input) {
  return Object.freeze({
    layer: "generic-incubator",
    version: KIT_CONTRACT_VERSION,
    graduationStatus: "local-incubation",
    reset: defaultReset,
    graduationRule: defaultGraduationRule,
    ...input,
  });
}

function createGoldRushContract(input) {
  return Object.freeze({
    layer: "goldrush-custom",
    version: KIT_CONTRACT_VERSION,
    graduationStatus: "game-specific",
    validator: "tools/validation/validate-domain-kit-contracts.mjs",
    reset: input.reset ?? "Reset game-specific state through the owning GoldRush runtime phase or match restart.",
    graduationRule: "Not promotable as-is because it owns GoldRush naming, rules, tuning, content, or presentation.",
    ...input,
  });
}

